-- 2026-10-12_platforms_table.sql
-- Dynamic publish platforms table for team & owner management

create table if not exists platforms (
  id bigint generated by default as identity primary key,
  organization_id uuid references organizations(id) on delete cascade,
  name text not null,
  code text not null,
  created_at timestamptz default now()
);

-- Index by organization
create index if not exists idx_platforms_org on platforms(organization_id);

-- Enable RLS
alter table platforms enable row level security;

-- 1. Any member of the organization can view platforms
drop policy if exists "platforms_select" on platforms;
create policy "platforms_select" on platforms
  for select using (
    organization_id is null or
    organization_id in (select organization_id from team_members where auth_user_id = auth.uid())
  );

-- 2. Only Owners and Managers can insert new platforms
drop policy if exists "platforms_insert" on platforms;
create policy "platforms_insert" on platforms
  for insert with check (
    organization_id in (
      select organization_id from team_members 
      where auth_user_id = auth.uid() and role in ('owner', 'manager')
    )
  );

-- 3. Only Owners and Managers can delete platforms
drop policy if exists "platforms_delete" on platforms;
create policy "platforms_delete" on platforms
  for delete using (
    organization_id in (
      select organization_id from team_members 
      where auth_user_id = auth.uid() and role in ('owner', 'manager')
    )
  );
